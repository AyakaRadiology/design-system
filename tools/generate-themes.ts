/**
 * Build the theme sets in themes/ from the voices they bundle.
 *
 * A voice declares its palette on `:root`, so two voices cannot share a page:
 * the second import simply wins. An app that lets its user choose between
 * voices at runtime needs every palette behind its own selector instead, and
 * that is what a theme set is: each member voice's `:root` block copied, value
 * for value, under `:root[data-theme="<name>"]`, plus the default member again
 * on bare `:root` so the page is styled before any attribute is set.
 *
 * The voices stay the source of truth and stay the thing the contrast floors in
 * src/lint/voices.test.ts check; this file only rearranges them. That is why the
 * set is generated rather than written: a hand-kept copy would drift from the
 * gated values the first time someone retuned a voice. `--check` regenerates in
 * memory and compares bytes, and runs in `bun run check`.
 *
 *   bun tools/generate-themes.ts           # write themes/*.css
 *   bun tools/generate-themes.ts --check   # fail if a committed set is stale
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));

export interface ThemeSet {
    /** Output file: themes/<name>.css. */
    name: string;
    /** The member drawn on bare `:root` (no data-theme yet, or an unknown one). */
    defaultTheme: string;
    /** data-theme value → voice file in voices/ (without .css). */
    members: Record<string, string>;
}

export const THEME_SETS: ThemeSet[] = [
    {
        name: "catppuccin",
        defaultTheme: "macchiato",
        members: {
            latte: "catppuccin-latte",
            frappe: "catppuccin-frappe",
            macchiato: "catppuccin-macchiato",
            mocha: "catppuccin-mocha",
        },
    },
];

const COMMENT = /\/\*[\s\S]*?\*\//g;

/** The body of the voice's single `:root` block, comments removed. */
export function rootBody(css: string, file: string): string {
    const code = css.replace(COMMENT, "");
    const at = code.indexOf(":root");
    const open = at === -1 ? -1 : code.indexOf("{", at);
    if (open === -1) throw new Error(`${file} declares no :root block`);
    if (code.indexOf(":root", open) !== -1)
        throw new Error(`${file} declares :root twice; a theme set takes one palette per voice`);
    if (/\.dark\s*\{/.test(code))
        throw new Error(`${file} has a .dark block; a theme set member must be single-mode`);
    let depth = 0;
    for (let i = open; i < code.length; i++) {
        if (code[i] === "{") depth++;
        else if (code[i] === "}" && --depth === 0)
            return code
                .slice(open + 1, i)
                .split("\n")
                .map((line) => line.trimEnd())
                .filter((line) => line.trim().length > 0)
                .join("\n");
    }
    throw new Error(`${file} has an unterminated :root block`);
}

export function renderSet(set: ThemeSet, readVoice: (voice: string) => string): string {
    const defaultVoice = set.members[set.defaultTheme];
    if (!defaultVoice)
        throw new Error(`${set.name}: default "${set.defaultTheme}" is not one of its members`);
    const lines = [
        `/* Theme set: ${set.name} — GENERATED by tools/generate-themes.ts. Do not edit:`,
        " * change the member voice and regenerate.",
        " *",
        ` * Put data-theme on <html> to choose a member: ${Object.keys(set.members)
            .map((theme) => `"${theme}"`)
            .join(", ")}.`,
        ` * Bare :root (no attribute yet) draws "${set.defaultTheme}". Each block is its voice's`,
        " * :root, value for value, so the contrast floors that hold the voice hold here.",
        " * An app override for one member uses the same selector as that member.",
        " */",
        "",
        '@import "../tokens/scales.css";',
        '@import "../tokens/glass.css";',
        "",
    ];
    const block = (selector: string, voice: string) => {
        lines.push(`/* voices/${voice}.css */`, `${selector} {`);
        lines.push(rootBody(readVoice(voice), `voices/${voice}.css`), "}", "");
    };
    block(":root", defaultVoice);
    for (const [theme, voice] of Object.entries(set.members))
        block(`:root[data-theme="${theme}"]`, voice);
    return `${lines.join("\n").trimEnd()}\n`;
}

function main(args: string[]): void {
    if (args.length && (args.length !== 1 || args[0] !== "--check"))
        throw new Error("Usage: bun tools/generate-themes.ts [--check]");
    const readVoice = (voice: string) => readFileSync(`${ROOT}voices/${voice}.css`, "utf8");
    let stale = 0;
    for (const set of THEME_SETS) {
        const path = `${ROOT}themes/${set.name}.css`;
        const next = renderSet(set, readVoice);
        if (args[0] === "--check") {
            const current = existsSync(path) ? readFileSync(path, "utf8") : null;
            if (current !== next) {
                console.error(
                    `::error::themes/${set.name}.css is missing or stale. Run \`bun run themes:generate\` and commit the result.`,
                );
                stale += 1;
            }
        } else {
            writeFileSync(path, next);
            console.log(`  wrote themes/${set.name}.css`);
        }
    }
    if (stale > 0) process.exitCode = 1;
}

if (import.meta.main) main(process.argv.slice(2));
